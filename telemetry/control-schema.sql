 values(p_device,p_metadata->>'version',p_metadata->>'boot',nullif(p_metadata->>'job','')::uuid)
 on conflict(device) do update set version=excluded.version,boot_id=excluded.boot_id,job_id=excluded.job_id,received_at=now();
end $function$

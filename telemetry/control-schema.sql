CREATE OR REPLACE FUNCTION public.ch1_ota_queue(p_user uuid, p_grant text, p_id uuid, p_release uuid)
 RETURNS uuid
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare grant_user uuid; boot text;
begin

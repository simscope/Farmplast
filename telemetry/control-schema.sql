CREATE OR REPLACE FUNCTION ch1_private.exchange(m jsonb, discover boolean)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare response jsonb; manifest jsonb; secret text; signed text; canonical text; job uuid;
begin
 if m is null or octet_length(m::text)>1024 or m->>'protocol' is distinct from '2'
 or coalesce(m->>'version','') !~ '^[A-Za-z0-9._-]{1,48}$' or coalesce(m->>'boot','') !~ '^[0-9a-f]{32}$'
 or coalesce(m->>'job','') !~ '^([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})?$'
 or coalesce(m->>'status','') not in ('idle','authorized','downloading','verifying','installing','rebooting','waiting_for_telemetry','completed','failed')
 or coalesce(m->>'progress','') !~ '^(100|[0-9]{1,2})$' then raise exception 'Invalid metadata'; end if;
 job=nullif(m->>'job','')::uuid;
 if not discover and (job is null or not exists(select 1 from public.ch1_ota_jobs where id=job)) then raise exception 'Unknown job'; end if;
 response=public.ch1_device_sync(m->>'version',m->>'boot',job,m->>'status',(m->>'progress')::int);
 update public.ch1_ota_device set protocol=2 where id='ESP32-CH1';
 manifest=response->'o';
 if discover and manifest is not null and manifest<>'null'::jsonb then
  select url into signed from ch1_private.downloads where job_id=(manifest->>'id')::uuid and expires_at>now();
  select device_key into secret from ch1_private.config where singleton;
  if signed is null or secret is null then raise exception 'Download not provisioned'; end if;
  canonical=(manifest->>'id')||'|update|CH1-ESP32S3-v1|'||(manifest->>'version')||'|'||(manifest->>'sha256')||'|'||(manifest->>'size')||'|'||(manifest->>'expires');
  response=jsonb_set(response,'{o}',(manifest-'path')||jsonb_build_object('url',signed,'mac',encode(extensions.hmac(canonical,secret,'sha256'),'hex')));
 else response=response-'o'; end if;
 return response;
end $function$
;
CREATE OR REPLACE FUNCTION ch23_ota_private.exchange(p_device text, m jsonb, discover boolean)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare response jsonb; manifest jsonb; signed text; secret text; canonical text; job uuid; state text; progress integer;
begin
 if m is null or octet_length(m::text)>1024 or m->>'protocol' is distinct from '2'
 or coalesce(m->>'version','') !~ '^[A-Za-z0-9._-]{1,48}$' or coalesce(m->>'boot','') !~ '^[0-9a-f]{32}$'
 or coalesce(m->>'job','') !~ '^([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})?$'
 or coalesce(m->>'status','') not in ('idle','authorized','downloading','verifying','installing','rebooting','waiting_for_telemetry','completed','failed')
 or coalesce(m->>'progress','') !~ '^(100|[0-9]{1,2})$' then raise exception 'Invalid device metadata'; end if;
 job=nullif(m->>'job','')::uuid;state=m->>'status';progress=(m->>'progress')::integer;
 if not discover and (job is null or not exists(select 1 from public.chiller_ota_jobs where id=job and device=p_device)) then raise exception 'Unknown device job'; end if;
 if state='failed' and m ? 'failure_code' then
  response=public.chiller_device_sync_diagnostic(p_device,m->>'version',m->>'boot',job,state,progress,m->>'failure_code');
 else response=public.chiller_device_sync(p_device,m->>'version',m->>'boot',job,state,progress); end if;
 update public.chiller_ota_devices set protocol=2,reset_reason=case when m->>'reset' in ('power_on','software','panic','interrupt_watchdog','task_watchdog','brownout','other') then m->>'reset' else 'other' end where device=p_device;
 manifest=response->'o';
 if discover and manifest is not null and manifest<>'null'::jsonb then
  select d.url,k.key into signed,secret from ch23_ota_private.downloads d cross join ch23_ota_private.device_keys k
  where d.job_id=(manifest->>'id')::uuid and k.device=p_device and d.expires_at>now()+interval '30 seconds';
  if signed is not null and secret is not null then
   manifest=(manifest-'path')||jsonb_build_object('url',signed);
   canonical=concat_ws('|',manifest->>'id','update',p_device,manifest->>'model',manifest->>'version',manifest->>'sha256',manifest->>'size',manifest->>'expires',signed);
   manifest=manifest||jsonb_build_object('mac',encode(extensions.hmac(canonical,secret,'sha256'),'hex'));
  else manifest=null; end if;
 else manifest=null; end if;
 response=jsonb_build_object('o',manifest)||case when response->>'a' in ('completed','failed') then jsonb_build_object('a',response->>'a') else '{}'::jsonb end;
 return response;
end $function$
;
CREATE OR REPLACE FUNCTION nj_msi_private.auth_device(p_device text, p_key text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare expected text;
begin
 if p_key is null or length(p_key) not between 16 and 256 then return false; end if;
 if p_device='ESP32-CH1' then
  select device_key into expected from ch1_private.config where singleton;
 else
  if p_device not in ('ESP32-CH2-PLC','ESP32-CH3-PLC') then return false; end if;
  select device_secret into expected from public.devices where device_code=p_device and coalesce(is_active,true);
 end if;
 return expected is not null and extensions.digest(p_key,'sha256')=extensions.digest(expected,'sha256');
end $function$
;
CREATE OR REPLACE FUNCTION public.ch1_command(p_id uuid, p_type text, p_value jsonb, p_pin text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare patch jsonb; hashed text; n numeric;
begin
 if not public.ch1_firmware_operator() then return jsonb_build_object('error','access_denied'); end if;
 if p_id is null then raise exception 'Request identity required'; end if;
 case
 when p_type='fan_mode' and p_value in ('"auto"'::jsonb,'"manual"'::jsonb) then patch=jsonb_build_object('auto',p_value='"auto"'::jsonb);
 when p_type='fan_off' then patch='{"auto":false,"fan_enable":false,"fan_30":false,"fan_60":false}';
 when p_type='fan_speed' and p_value in ('30'::jsonb,'60'::jsonb,'"30"'::jsonb,'"60"'::jsonb) then patch=jsonb_build_object('auto',false,'fan_enable',true,'fan_30',(p_value#>>'{}')::int=30,'fan_60',(p_value#>>'{}')::int=60);
 when p_type in ('fan_setpoint','d1','d2','hyst') and jsonb_typeof(p_value) in ('number','string') then
  n=(p_value#>>'{}')::numeric;
  if n='NaN'::numeric or n not between (case when p_type='fan_setpoint' then -100 else 0 end) and (case when p_type='fan_setpoint' then 300 else 100 end) then raise exception 'Invalid threshold'; end if;
  patch=jsonb_build_object(case when p_type='fan_setpoint' then 'setpoint' else p_type end,n);
 when p_type='reset_alert' then
  -- Failed PIN attempts return normally so the rate-limit record commits.
  if not public.ch1_ota_attempt(auth.uid()) then return jsonb_build_object('error','rate_limited'); end if;
  select code_hash into hashed from ch1_private.config where singleton;
  if p_pin is null or p_pin !~ '^[0-9]{4}$' or hashed is null or extensions.crypt(p_pin,hashed)<>hashed then return jsonb_build_object('error','invalid_code'); end if;
  patch='{"reset":true}';
 else raise exception 'Invalid command';
 end case;
 return jsonb_build_object('command',public.ch1_control_request(auth.uid(),p_id,p_type,patch));
end $function$
;
create or replace function public.ch1_control_reconcile() returns void language plpgsql set search_path='' as $$ begin update public.ch1_control_commands set status='timeout' where status='pending' and expires_at<=now(); end $$;
CREATE OR REPLACE FUNCTION public.ch1_control_request(p_user uuid, p_id uuid, p_type text, p_patch jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare d public.ch1_desired_state; existing public.ch1_control_commands; next_values jsonb;
begin
 perform pg_catalog.pg_advisory_xact_lock(714001);
 select * into existing from public.ch1_control_commands where id=p_id;
 if existing.id is not null then
   if existing.operator_id<>p_user or existing.command_type<>p_type or existing.requested<>p_patch then raise exception 'Request id conflict'; end if;
   return to_jsonb(existing);
 end if;
 update public.ch1_control_commands set status='timeout' where status='pending' and expires_at<=now();
 if exists(select 1 from public.ch1_control_commands where status='pending') then raise exception 'Previous command pending'; end if;
 if not exists(select 1 from public.ch1_ota_device where last_seen>now()-interval '30 seconds') then raise exception 'ESP32 offline'; end if;
 if exists(select 1 from public.ch1_ota_jobs where status not in ('completed','failed') and expires_at>now()) then raise exception 'Programming active'; end if;
 if p_type not in ('fan_mode','fan_off','fan_speed','fan_setpoint','d1','d2','hyst','reset_alert') or jsonb_typeof(p_patch)<>'object' or p_patch='{}'::jsonb then raise exception 'Invalid command'; end if;
 if exists(select 1 from jsonb_object_keys(p_patch) k where k not in ('auto','fan_enable','fan_30','fan_60','setpoint','d1','d2','hyst','reset')) then raise exception 'Invalid command field'; end if;
 select * into d from public.ch1_desired_state where id='ESP32-CH1' for update;
 next_values=d.values||(p_patch-'reset');
 if exists(select 1 from jsonb_each(next_values) x where (x.key in ('auto','fan_enable','fan_30','fan_60') and jsonb_typeof(x.value)<>'boolean') or (x.key in ('setpoint','d1','d2','hyst') and jsonb_typeof(x.value)<>'number')) then raise exception 'Invalid field type'; end if;
 if (next_values->>'setpoint')::numeric not between -100 and 300 or (next_values->>'d1')::numeric not between 0 and 100 or (next_values->>'d2')::numeric not between 0 and 100 or (next_values->>'hyst')::numeric not between 0 and 100 or (next_values->>'d2')::numeric<(next_values->>'d1')::numeric then raise exception 'Invalid threshold range'; end if;
 update public.ch1_desired_state set values=next_values,revision=revision+1,reset_sequence=reset_sequence+case when p_type='reset_alert' then 1 else 0 end,updated_at=now() where id=d.id returning * into d;
 insert into public.ch1_control_commands(id,operator_id,command_type,requested,revision,reset_sequence) values(p_id,p_user,p_type,p_patch,d.revision,d.reset_sequence) returning * into existing;
 insert into public.ch1_ota_events(operator_id,event) values(p_user,'control_requested:'||p_id::text);
 return to_jsonb(existing);
end $function$
;
CREATE OR REPLACE FUNCTION public.ch1_device_sync(p_version text, p_boot text, p_job uuid, p_status text, p_progress integer)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare j public.ch1_ota_jobs; points jsonb; manifest jsonb; ack text; current_rank integer; next_rank integer; desired public.ch1_desired_state; reset_request integer;
begin
  perform pg_catalog.pg_advisory_xact_lock(714001);
  insert into public.ch1_ota_device(id,version,boot_id) values('ESP32-CH1',p_version,p_boot)
  on conflict(id) do update set version=excluded.version,boot_id=excluded.boot_id,last_seen=now();
  select * into j from public.ch1_ota_jobs where id=p_job for update;
  if j.id is not null and j.status not in ('completed','failed') then
    current_rank=array_position(array['authorized','downloading','verifying','installing','rebooting','waiting_for_telemetry'],j.status);
    next_rank=array_position(array['authorized','downloading','verifying','installing','rebooting','waiting_for_telemetry'],p_status);
    if p_status='failed' then
      update public.ch1_ota_jobs set status='failed',failure='device_reported_failure',updated_at=now() where id=j.id;
    elsif next_rank>=current_rank and p_progress between 0 and 100 and
      ((p_boot=j.source_boot and p_status<>'waiting_for_telemetry') or
       (p_boot<>j.source_boot and p_status='waiting_for_telemetry' and exists(select 1 from public.ch1_ota_releases where id=j.release_id and version=p_version))) then
      update public.ch1_ota_jobs set status=p_status,progress=greatest(progress,p_progress),updated_at=now() where id=j.id;
    end if;
    -- Completion requires a NEW boot, the selected version, and an actual telemetry row
    -- written by that boot. A status-only heartbeat cannot complete an update.
    if exists(select 1 from public.ch1_ota_jobs where id=j.id and status='waiting_for_telemetry') and p_boot<>j.source_boot and exists(select 1 from nj_msi_private.ch1_receipt t join public.ch1_ota_releases r on r.id=j.release_id where t.device='ESP32-CH1' and t.version=p_version and t.boot_id=p_boot and t.job_id=p_job and r.version=p_version and t.received_at>now()-interval '16 seconds') then
      update public.ch1_ota_jobs set status='completed',progress=100,updated_at=now() where id=j.id;
    end if;
  end if;
  update public.ch1_ota_jobs set status='failed',failure='deadline_exceeded',updated_at=now() where status not in ('completed','failed') and expires_at<=now();
  update public.ch1_ota_jobs jobs set status='failed',failure='release_revoked',updated_at=now() where status='authorized' and not exists(select 1 from public.ch1_ota_releases r where r.id=jobs.release_id and approved);
  select status into ack from public.ch1_ota_jobs where id=p_job;
  perform public.ch1_control_reconcile();
  select * into desired from public.ch1_desired_state where id='ESP32-CH1';
  points=desired.values;
  if exists(select 1 from public.ch1_control_commands where command_type='reset_alert' and status='pending' and expires_at>now()) then reset_request=desired.reset_sequence; end if;
  select jsonb_build_object('id',jobs.id,'action','update','expires',floor(extract(epoch from jobs.expires_at))::bigint,
    'version',r.version,'sha256',r.sha256,'size',r.size,'path',r.storage_path,'model',r.model)
  into manifest from public.ch1_ota_jobs jobs join public.ch1_ota_releases r on r.id=jobs.release_id
  where jobs.status='authorized' and jobs.expires_at>now() and r.approved order by jobs.created_at limit 1;
  return jsonb_build_object('c',jsonb_build_array(points->'setpoint',points->'d1',points->'d2',points->'hyst',points->'auto',points->'fan_enable',points->'fan_30',points->'fan_60',false),'o',manifest,'a',ack,'r',desired.revision,'q',reset_request);
end $function$
;
